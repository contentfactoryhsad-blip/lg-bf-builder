const withFades = (p: BoardPlacement | undefined, fades?: PaidFade[]): PaidPlacement | null =>
  p ? (fades ? { ...p, fades } : p) : null;

export function paidPlacementFor(assetId: string, sizeKey: string): PaidPlacement | null {
  if (isPdSlotAsset(assetId)) {
    const p = PD_SLOT_PLACEMENT[sizeKey];
    return p ? { ...p, artId: pdSlotArtId(assetId, p.ver) } : null;
  }
  if (PD_CENTRIC_ASSETS.has(assetId)) return PD_CENTRIC_PLACEMENT[sizeKey] ?? null;
  if (DEAL_AD_ASSETS.has(assetId)) return withFades(DEAL_AD_PLACEMENT[sizeKey], DEAL_AD_FADES[sizeKey]);
  if (assetId === AD_BENEFIT_ASSET) return withFades(AD_BENEFIT_PLACEMENT[sizeKey], AD_BENEFIT_FADES[sizeKey]);
  return null;
}
