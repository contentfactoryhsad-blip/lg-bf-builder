export const paidSlotsForAsset = (_assetId: string, channelKey: string): PaidSlot[] =>
  paidSlotsFor(channelKey);

/**
 * Board 002 = `External Banner Black Friday_Key Visual_Product Slot 4_1026`. Its
 * `Black Friday Image — PD Slot 4` master got its own cut (2026-10-28) — the
 * visible fill, not the hidden Main one under it. The character variant is a
 * CROP fill on the board, so its file was cut to the same window before export.
 */
const V2_ART = { plain: 'kv-pd-slot2', character: 'kv-pd-slot2-character' } as const;

/**
 * Board 001 = `…Product Slot 3_1026`, master `Black Friday Image — PD Slot 3`.
 * Re-arted again for the 1026 boards (2026-10-28): the visible fill is a new cut,
 * byte-different from `kv-product-slot001`. Compare bytes, not eyes.
 */
const V1_ART = { plain: 'kv-pd-slot1', character: 'kv-pd-slot1-character' } as const;

/**
 * Which artwork file a size loads. The board decides the version; the chosen
 * asset decides whether the character is in the frame.
 */
export function pdSlotArtId(assetId: string, ver: 'v1' | 'v2'): string {
  const key = assetId.endsWith('-character') ? 'character' : 'plain';
  return ver === 'v2' ? V2_ART[key] : V1_ART[key];
}

export const pdSlotFor = (assetId: string, sizeKey: string): PdSlotPlacement | null =>
  isPdSlotAsset(assetId) ? PD_SLOT_PLACEMENT[sizeKey] ?? null : null;

/** Most sizes carry four plates; `dv360-970x90` carries two. */
export const pdPlateCount = (assetId: string) =>
  isPdSlotAsset(assetId)
    ? Object.values(PD_SLOT_PLACEMENT).reduce((m, p) => Math.max(m, p.plates.length), 0)
    : 0;

