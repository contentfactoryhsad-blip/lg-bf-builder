/**
 * LG.com frames as the 1026 boards stack them — one layer list per key visual
 * per size, in Figma's z-order (first = bottom).
 *
 * Source: `miJcDQgz0yJMskLE5a5HHj`, page "Banner Template 3", the
 * `LG.com — <asset>_1026` sections (read 2026-10-27). Each frame there is the KV
 * instance, black fade rectangles ("Gradation", "KV edge fade"), the size's
 * layout instance and — on the boards whose artwork leaves it out — the
 * "Only at LG.com" text, with the order changing from size to size. Some frames
 * put the artwork ABOVE the copy (1600×400, 1920×300), some put the fades BELOW
 * the artwork where they do nothing; both are reproduced as drawn rather than
 * tidied, so the preview matches the board.
 *
 *   A  the artwork square (x, y, size — a fourth number when Figma's box is not
 *      square; the image fills and centre-crops it, see `A`)
 *   G  a black fade rect in frame px: CSS angle + [position, alpha] stops
 *   MK a white gradient used as a MASK on the artwork (Bundle 720×480 only)
 *   L  the layout — icon row, copy, CTA, indicator, disclaimer
 *   T  "Only at LG.com", frame px box + font size
 *
 * The Product Slot and Dynamic boards are not here: Product Slot is on hold
 * (its 1026 boards were laid out wrong) and Dynamic runs only its three video
 * sizes, so both keep the older per-size tables in `lgcomSlots.ts`.
 *
 * 2026-10-27: the user re-framed four mobile sizes on Main (720×960, 720×830,
 * 720×750, PR0015 572×800 — KV and tagline only, the fades stayed) and the
 * same KV went onto Character / Hero Product / Non AC, each tagline keeping its
 * own spot on its lockup. A second pass the same day did the same for
 * ST0004 586×842 / 464×409 / 342×409 / 720×480 and ST0047 720×420.
 *
 * Re-read from Figma rather than hand-editing — the values came out of a
 * read-only `use_figma` pass, one row per frame.
 */

export type FrameLayer =
  | { k: 'a'; x: number; y: number; w: number; h: number }
  | { k: 'g'; x: number; y: number; w: number; h: number; angle: number; stops: [number, number][] }
  | { k: 'mask'; x: number; y: number; w: number; h: number; angle: number; stops: [number, number][] }
  | { k: 'l' }
  | { k: 't'; x: number; y: number; w: number; h: number; size: number };

/**
 * A KV instance Figma resized out of square still shows its image in FILL mode —
 * scaled to cover the box and centre-cropped, never stretched. So a 786×894 box
 * is a 894 square centred on it; the box itself only clips, and the frame clips
 * anyway. Normalised here so every consumer can keep treating the art as square.
 */
const A = (x: number, y: number, w: number, h = w): FrameLayer => {
  const s = Math.max(w, h);
  return { k: 'a', x: x + (w - s) / 2, y: y + (h - s) / 2, w: s, h: s };
};
const G = (x: number, y: number, w: number, h: number, angle: number, stops: [number, number][]): FrameLayer =>
  ({ k: 'g', x, y, w, h, angle, stops });
const MK = (x: number, y: number, w: number, h: number, angle: number, stops: [number, number][]): FrameLayer =>
  ({ k: 'mask', x, y, w, h, angle, stops });
const L: FrameLayer = { k: 'l' };
const T = (x: number, y: number, w: number, h: number, size: number): FrameLayer => ({ k: 't', x, y, w, h, size });

